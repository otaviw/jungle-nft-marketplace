import { test, expect } from '@playwright/test'
import { login } from './helpers'

test('mercado aceita cliques repetidos e acompanha a seção visível', async ({ page }) => {
    test.skip((page.viewportSize()?.width ?? 0) < 768, 'Menu superior desktop')
    await page.goto('/')
    await expect(page.locator('#catalogo article')).toHaveCount(9)
    const market = page.getByRole('navigation', { name: 'Navegação principal' }).getByRole('link', { name: 'Mercado', exact: true })
    await market.click()
    await expect(market).toHaveAttribute('aria-current', 'location')
    await page.evaluate(() => window.scrollTo(0, 0))
    await expect(page.getByRole('navigation', { name: 'Navegação principal' }).getByRole('link', { name: 'Início', exact: true })).toHaveAttribute('aria-current', 'location')
    await market.click()
    await expect.poll(() => page.locator('#catalogo').evaluate(el => el.getBoundingClientRect().top)).toBeLessThan(160)
    await expect(market).toHaveAttribute('aria-current', 'location')
})

test('perfil e carteiras oferecem saída explícita no mobile', async ({ page }) => {
    test.skip((page.viewportSize()?.width ?? 0) >= 768, 'Navegação mobile')
    await login(page, 'demo@kurio.test', '/profile')
    await page.getByRole('link', { name: 'Voltar ao catálogo', exact: true }).click()
    await expect(page).toHaveURL(/\/(?:\?.*)?(?:#catalogo)?$/)
    await page.goto('/wallets')
    await page.getByRole('link', { name: 'Voltar ao catálogo', exact: true }).click()
    await expect(page.locator('#catalogo')).toBeVisible()
})

test('favoritos filtram na API, persistem e desaparecem ao remover', async ({ page }) => {
    await login(page)
    await page.goto('/nfts/nft-001')
    const favorite = page.getByRole('button', { name: /^(Adicionar aos favoritos|Remover dos favoritos|Favoritar)$/ })
    await expect(favorite).toBeEnabled()
    await favorite.click()
    await expect(favorite).toHaveAttribute('aria-pressed', 'true')
    await expect(page.getByText('Favorito atualizado', { exact: true })).toBeAttached()
    await page.goto('/?favorites=true')
    await expect(page.locator('#catalogo article')).toHaveCount(1)
    await page.reload()
    await expect(page.locator('#catalogo article')).toHaveCount(1)
    await page.locator('#catalogo').getByRole('button', { name: 'Remover dos favoritos', exact: true }).click()
    await expect(page.getByText('Você ainda não tem favoritos com estes filtros.', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Somente favoritos', exact: true }).click()
    await expect(page.locator('#catalogo article')).toHaveCount(9)
})

test('abas mudam o catálogo e a ordenação não volta ao topo', async ({ page }) => {
    await page.goto('/')
    await expect(page.locator('#catalogo article')).toHaveCount(9)
    await page.getByRole('tab', { name: 'Novos lançamentos', exact: true }).click()
    await expect(page).toHaveURL(/[?&]view=new/)
    await expect(page.locator('#catalogo article')).toHaveCount(6)
    await page.getByRole('tab', { name: 'Em alta', exact: true }).click()
    await expect(page).toHaveURL(/[?&]view=trending/)
    await expect(page.locator('#catalogo article')).toHaveCount(9)
    await page.getByRole('tab', { name: 'Todos os NFTs', exact: true }).click()
    if ((page.viewportSize()?.width ?? 0) < 768) await page.getByRole('button', { name: 'Abrir filtros', exact: true }).click()
    await page.locator('#catalogo').evaluate(element => window.scrollTo(0, window.scrollY + element.getBoundingClientRect().top - 110))
    const beforeSort = await page.evaluate(() => scrollY)
    await page.getByRole('combobox', { name: 'Ordenar por', exact: true }).click()
    await page.getByRole('option', { name: 'Menor preço', exact: true }).click()
    await expect(page).toHaveURL(/[?&]sort=price-asc/)
    expect(beforeSort).toBeGreaterThan(100)
    await expect.poll(() => page.evaluate(() => scrollY)).toBeGreaterThan(100)
})

