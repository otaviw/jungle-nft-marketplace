import { test, expect } from '@playwright/test'

test('galeria seleciona recortes, amplia a imagem e mantém a seleção de edição e quantidade', async ({ page }) => {
    await page.goto('/nfts/nft-002')
    await expect(page.getByRole('heading', { name: 'Sage Nomad #002', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Comprar NFT — adicionar ao carrinho', exact: true }))
        .toHaveAccessibleName(/Comprar NFT/)
    const image = page.getByRole('img', { name: 'Sage Nomad #002 — imagem principal', exact: true })
    await expect(image).toBeVisible()
    const mobile = page.viewportSize()!.width < 768
    if (mobile) await page.getByRole('button', { name: 'Ampliar imagem do NFT', exact: true }).click()
    const detail = page.getByRole('button', { name: 'Ver detalhe do rosto', exact: true })
    await detail.click()
    await expect(detail).toHaveAttribute('aria-pressed', 'true')
    await expect(page.getByRole('button', { name: 'Ver imagem completa', exact: true })).toHaveAttribute('aria-pressed', 'false')
    if (mobile) await page.keyboard.press('Escape')
    await expect(image).toHaveAttribute('data-view', 'face')
    await page.getByRole('button', { name: 'Ampliar imagem do NFT', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: 'Imagem ampliada de Sage Nomad #002' })
    await expect(dialog).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(dialog).not.toBeVisible()
    await expect(page.getByRole('button', { name: 'Ampliar imagem do NFT', exact: true })).toBeFocused()
    await page.getByRole('radio', { name: 'Edição limitada', exact: true }).check()
    await expect(page.getByLabel('Quantidade', { exact: true })).toHaveAttribute('max', '2')
    await page.getByRole('button', { name: 'Aumentar quantidade', exact: true }).click()
    await expect(page.getByLabel('Quantidade', { exact: true })).toHaveValue('2')
    await expect(page.getByRole('button', { name: 'Aumentar quantidade', exact: true })).toBeDisabled()
    await page.getByRole('button', { name: 'Diminuir quantidade', exact: true }).click()
    await expect(page.getByLabel('Quantidade', { exact: true })).toHaveValue('1')

    const details = page.getByRole('tab', { name: 'Detalhes do NFT', exact: true })
    const reviews = page.getByRole('tab', { name: 'Avaliações de colecionadores', exact: true })
    await reviews.click()
    await expect(page.getByRole('tabpanel').getByRole('list', { name: 'Comentários de colecionadores', exact: true }).getByRole('listitem')).toHaveCount(3)
    await page.keyboard.press('Home')
    await expect(details).toHaveAttribute('aria-selected', 'true')
    await expect(details).toBeFocused()
    await page.keyboard.press('End')
    await expect(reviews).toHaveAttribute('aria-selected', 'true')
    await page.keyboard.press('ArrowRight')
    await expect(details).toHaveAttribute('aria-selected', 'true')
})
